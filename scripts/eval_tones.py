"""Upgraded objective evaluation suite (Phase 4, `improvements.md` Stage 6).

Six checks required by the blueprint, all measured against the source stem:

  1. Per-Key Pitch Audit      - >= 95% of keys within +-25 cents, and ZERO
                                octave/fifth misdetections.
  2. Key-to-Key Timbre Coherence - max adjacent-key jump in centroid/f0 < 25%
                                (the old slicer measured 142%) and note-length
                                variance < 1.3x.
  3. Octave-Band Spectral Match - 8-band error profile (63 Hz..8 kHz) in dB vs
                                the source stem (replaces the single-number
                                centroid comparison, which bad spectra can fool).
  4. Polyphonic Chord Clarity  - render C4-E4-G4 and verify no clipping / mud.
  5. Null Test                 - for sampled instruments: residual < -60 dBFS and
                                correlation >= 0.99.
  6. Per-Song Disk Budget      - total generated bytes < 1.2 GB.

Why a separate module: `tone_eval.py` drives the tone through the VST3 plugins,
and headless VST sample loading is broken in this environment (measured: sfizz
cannot be fed an .sfz through pedalboard's state APIs, and sforzando renders
silence even for the project's own Salamander piano). This suite therefore
evaluates the per-key WAVs that `build_song_tone.py` actually produces - which is
also the artifact Cantabile will load - so the numbers are reproducible here.

Usage:
  python eval_tones.py --song "韦礼安 - 女孩"
  python eval_tones.py --song "..." --json out.json
"""
