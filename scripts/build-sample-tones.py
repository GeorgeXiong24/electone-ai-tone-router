"""Build sample-based single-instrument tones from the separated stems.

Surge XT is a synthesizer: no sampled-instrument playback, so factory presets
cannot sound like the original recording. This script instead cuts real single
notes out of each stem and builds an SFZ instrument (sforzando) from them, so
the tone carries the actual instrument timbre of the song.

For every stem with a keyboard assignment the script writes:

  workspace/tone/<右手|左手|脚>/sforzando/<song> - <instrument>.sfz
  workspace/tone/<右手|左手|脚>/sforzando/samples/<song> - <instrument>/*.wav

Each .sfz + its sample folder holds exactly ONE instrument.

Note extraction: onset detection + f0 tracking (pyin); a note is kept when it
is pitch-stable, loud enough and at least 120 ms long. One sample per pitch is
kept (the loudest), regions cover +/- 2 semitones around each sampled pitch.

Usage:
  python build-sample-tones.py --song <title substring>
  python build-sample-tones.py --latest
  python build-sample-tones.py --analysis <analysis.json> --dry-run
"""
import argparse
import glob
import json
import os
import sys
import datetime

import numpy as np
import soundfile as sf

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORKSPACE = os.environ.get("ELECTONE_WORKSPACE") or os.path.join(ROOT, "workspace")
TONE_ROOT = os.path.join(WORKSPACE, "tone")

INSTRUMENT_ZH = {"vocals": "人声", "guitar": "吉他", "piano": "钢琴",
                 "bass": "贝斯", "other": "其他/混合"}

MAX_NOTES = 16
MIN_NOTE_SECONDS = 0.12
MAX_NOTE_SECONDS = 1.2
STABLE_SEMITONES = 0.7


def safe_name(v):
    import re
    return re.sub(r'[\\/:*?"<>|]', "-", v).strip()


def extract_notes(stem_path, sr=44100):
    """Return (audio, notes) where notes are dicts with midi/start/end/rms."""
    import librosa

    y, _ = librosa.load(stem_path, sr=sr, mono=True)
    if y.size == 0:
        return y, []

    hop = 512
    onset_frames = librosa.onset.onset_detect(
        y=y, sr=sr, hop_length=hop, backtrack=True)
    onsets = librosa.frames_to_samples(onset_frames, hop_length=hop)
    if len(onsets) == 0:
        return y, []

    f0, _, _ = librosa.pyin(y, fmin=41.2, fmax=2000.0, sr=sr,
                            frame_length=4096, hop_length=hop)
    rms = librosa.feature.rms(y=y, frame_length=2048, hop_length=hop)[0]

    notes = []
    for idx, start in enumerate(onsets):
        end = int(onsets[idx + 1]) if idx + 1 < len(onsets) else len(y)
        end = min(end, start + int(MAX_NOTE_SECONDS * sr))
        if (end - start) / sr < MIN_NOTE_SECONDS:
            continue
        a, b = start // hop, min(len(f0), end // hop)
        seg = f0[a:b]
        seg = seg[np.isfinite(seg)]
        if len(seg) < 3:
            continue
        midi = librosa.hz_to_midi(seg)
        if float(np.std(midi)) > STABLE_SEMITONES:
            continue
        r = float(rms[a:b].max()) if b > a else 0.0
        if r < 1e-3:
            continue
        notes.append({
            "midi": int(round(float(np.median(midi)))),
            "start": int(start),
            "end": int(end),
            "rms": r,
        })

    # keep the loudest take per pitch, then the loudest MAX_NOTES
    best = {}
    for n in notes:
        cur = best.get(n["midi"])
        if cur is None or n["rms"] > cur["rms"]:
            best[n["midi"]] = n
    picked = sorted(best.values(), key=lambda n: n["rms"], reverse=True)[:MAX_NOTES]
    return y, sorted(picked, key=lambda n: n["midi"])


def write_note_wav(y, note, path, sr=44100):
    seg = y[note["start"]:note["end"]].astype(np.float32).copy()
    peak = float(np.abs(seg).max())
    if peak > 0:
        seg /= peak
    fade = min(int(0.005 * sr), len(seg) // 4)
    if fade > 1:
        seg[:fade] *= np.linspace(0, 1, fade)
        seg[-fade:] *= np.linspace(1, 0, fade)
    sf.write(path, seg, sr, subtype="PCM_16")


def build_sfz(sfz_path, song, label, role, notes, rel_sample_dir):
    lines = [
        "// %s - %s (%s) / single instrument" % (song, label, role),
        "// Samples cut from the song's own stem; generated by scripts/build-sample-tones.py.",
        "// One instrument per file. Relative paths only (samples next to this sfz).",
        "",
        "<control>",
        "default_path=%s/" % rel_sample_dir,
        "",
        "<global>",
        "ampeg_attack=0.001",
        "ampeg_release=0.25",
        "amp_veltrack=60",
        "",
    ]
    # Contiguous key ranges split at the midpoints between sampled pitches, so
    # no key plays two samples at once.
    for i, n in enumerate(notes):
        lo = 0 if i == 0 else (notes[i - 1]["midi"] + n["midi"] + 1) // 2
        hi = 127 if i == len(notes) - 1 else (n["midi"] + notes[i + 1]["midi"]) // 2
        lines.append(
            f"<region> sample={n['midi']}.wav pitch_keycenter={n['midi']} "
            f"lokey={lo} hikey={hi} lovel=1 hivel=127")
    lines.append("")
    with open(sfz_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def role_for_keyboard(stem, keyboard):
    """Most relevant role of this stem that maps to the given keyboard."""
    rule = {"右手": ["主旋律"], "左手": ["副旋律", "和弦", "伴奏", "和声铺底"],
            "脚": ["低音线条"]}
    roles = stem.get("roles", {})
    best, best_share = None, -1.0
    for role, share in roles.items():
        if role in rule.get(keyboard, []) and share > best_share:
            best, best_share = role, share
    return best or stem.get("primary_role", "")


def build_song(song, stems, stems_dir, dry_run=False):
    entries = []
    for stem_name, stem in stems.items():
        if stem.get("empty") or stem_name == "drums":
            continue
        label = INSTRUMENT_ZH.get(stem_name)
        if label is None:
            continue
        if stem_name == "piano":
            # The piano stem already maps to the Accurate-Salamander grand
            # piano sample library (a full multisample), which is far better
            # than slicing notes out of the mix. Skip it here.
            continue
        stem_wav = os.path.join(stems_dir, f"{stem_name}.wav")
        if not os.path.isfile(stem_wav):
            print(f"  skip {label}: stem missing ({stem_wav})")
            continue

        y, notes = extract_notes(stem_wav)
        if not notes:
            print(f"  skip {label}: no stable notes found")
            continue
        print(f"  {label}: {len(notes)} notes, MIDI "
              f"{notes[0]['midi']}..{notes[-1]['midi']}")

        for keyboard in stem.get("keyboards", []):
            role = role_for_keyboard(stem, keyboard)
            plugin_dir = os.path.join(TONE_ROOT, keyboard, "sforzando")
            base = safe_name(f"{song} - {label}")
            sfz_path = os.path.join(plugin_dir, base + ".sfz")
            sample_dir = os.path.join(plugin_dir, "samples", base)
            if not os.path.abspath(sfz_path).startswith(
                    os.path.abspath(TONE_ROOT) + os.sep):
                raise RuntimeError(f"refusing to write outside tone dir: {sfz_path}")
            print(f"    {os.path.relpath(sfz_path, TONE_ROOT)}")
            if dry_run:
                entries.append({"sfz": os.path.relpath(sfz_path, TONE_ROOT),
                                "keyboard": keyboard, "instrument": label,
                                "role": role, "notes": len(notes), "dry_run": True})
                continue

            os.makedirs(sample_dir, exist_ok=True)
            for n in notes:
                write_note_wav(y, n, os.path.join(sample_dir, f"{n['midi']}.wav"))
            rel_sample_dir = "samples/" + base
            build_sfz(sfz_path, song, label, role, notes, rel_sample_dir)
            entries.append({
                "sfz": os.path.relpath(sfz_path, TONE_ROOT),
                "samples_dir": os.path.relpath(sample_dir, TONE_ROOT),
                "keyboard": keyboard, "instrument": label, "role": role,
                "notes": len(notes),
                "range": [notes[0]["midi"], notes[-1]["midi"]],
            })
    return entries


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--analysis", default="")
    ap.add_argument("--song", default="")
    ap.add_argument("--latest", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    path = args.analysis
    if not path:
        root = os.path.join(WORKSPACE, "analysis")
        cands = glob.glob(os.path.join(root, "*", "analysis.json"))
        if args.song:
            cands = [p for p in cands if args.song in os.path.basename(os.path.dirname(p))]
        if not cands:
            sys.exit(f"no analysis.json under {root} - run analyze-tones.py first")
        path = max(cands, key=os.path.getmtime)

    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    song = data["song"]
    stems_dir = data.get("stems_dir", "")
    print(f"song: {song}")
    print(f"stems: {stems_dir}")

    entries = build_song(song, data["stems"], stems_dir, dry_run=args.dry_run)

    if not args.dry_run:
        os.makedirs(TONE_ROOT, exist_ok=True)
        manifest_path = os.path.join(TONE_ROOT, "sample-instruments.json")
        manifest = {}
        if os.path.isfile(manifest_path):
            with open(manifest_path, encoding="utf-8") as f:
                manifest = json.load(f)
        manifest[song] = {
            "generated": datetime.datetime.now().isoformat(timespec="seconds"),
            "plugin": "sforzando",
            "note": "single instrument per .sfz; samples are cut from the stem itself",
            "files": entries,
        }
        with open(manifest_path, "w", encoding="utf-8") as f:
            json.dump(manifest, f, ensure_ascii=False, indent=2)
        print(f"\nwrote {len(entries)} sample instruments + {manifest_path}")
    else:
        print(f"\n[dry-run] would write {len(entries)} sample instruments")


if __name__ == "__main__":
    main()
